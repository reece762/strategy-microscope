def _m(d, k):
    if d is None:
        return None
    return d.get(k) if k in d else d.get(str(k))


def _k(v):
    """把美金金額縮寫成 k。"""
    return f'{v/1000:,.0f}k'


def _pc(v, nd=2):
    """比例 -> 百分比字串（不帶正負號）。"""
    return f'{v*100:.{nd}f}%'


